    private const val SALVAGE_LOW_CHANCE = 64
    private const val SALVAGE_HIGH_CHANCE = 192

    class WreckBuilder {
        private val coords = mutableListOf<Int>()
        private val angles = mutableListOf<Int>()
        private val objs = mutableListOf<String>()
        private val mins = mutableListOf<Int>()
        private val maxes = mutableListOf<Int>()
        private val weights = mutableListOf<Int>()

        fun spawn(x: Int, z: Int, angle: Int) {
            coords += CoordGrid(x, z, 0).packed
            angles += angle
        }

        fun loot(obj: String, min: Int, max: Int, weight: Int) {
            objs += obj
            mins += min
            maxes += max
            weights += weight
        }

        fun write(row: DBRowBuilder) {
            row.column(SPAWN_COORDS, coords)
            row.column(SPAWN_ANGLES, angles)
            row.columnRSCM(LOOT_OBJS, objs)
            row.column(LOOT_MIN, mins)
            row.column(LOOT_MAX, maxes)
            row.column(LOOT_WEIGHTS, weights)
        }
    }
